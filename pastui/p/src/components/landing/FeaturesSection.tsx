// ── CheckIcon ─────────────────────────────────────────────────────────────────
// Inline SVG — no icon library needed for a single icon.
// aria-hidden because the check is decorative; the text beside it is the content.
function CheckIcon() {
  return (
    <svg
      aria-hidden="true"
      className="mt-0.5 h-4 w-4 shrink-0 text-blue-500"
      fill="none"
      viewBox="0 0 24 24"
      stroke="currentColor"
      strokeWidth={2.5}
    >
      <path
        strokeLinecap="round"
        strokeLinejoin="round"
        d="M4.5 12.75l6 6 9-13.5"
      />
    </svg>
  )
}

// ── FeatureCard ───────────────────────────────────────────────────────────────
// Private sub-component — not exported. Only FeaturesSection uses it.
// Accepts all content via props so it can render either the dev or recruiter card
// without duplicating markup.
function FeatureCard({ id, badge, title, subtitle, features, badgeClass }: FeatureCardProps) {
  return (
    <div
      id={id}
      // scroll-mt-4 adds top margin when this element is scrolled to via
      // the #for-recruiters anchor link — prevents the content from sitting
      // right at the top edge of the viewport.
      className="scroll-mt-4 flex flex-col rounded-2xl border border-gray-200 bg-white p-8 shadow-sm"
    >
      {/* Card header */}
      <div className="mb-6">
        <span className={`inline-block rounded-full px-2.5 py-0.5 text-xs font-semibold ${badgeClass}`}>
          {badge}
        </span>
        <h3 className="mt-3 text-xl font-bold text-gray-900">{title}</h3>
        <p className="mt-1 text-sm text-gray-500">{subtitle}</p>
      </div>

      {/* Feature list */}
      <ul className="space-y-4">
        {features.map((feature) => (
          <li key={feature.title} className="flex gap-3">
            <CheckIcon />
            <div>
              <p className="text-sm font-semibold text-gray-800">{feature.title}</p>
              <p className="mt-0.5 text-xs leading-relaxed text-gray-500">
                {feature.description}
              </p>
            </div>
          </li>
        ))}
      </ul>
    </div>
  )
}

