// ── TypeScript interfaces ─────────────────────────────────────────────────────

/**
 * One feature row: a title + description pair.
 * Defined as an interface (not type) because it describes the shape
 * of a data object, which is the conventional use of interface in TS.
 */
interface Feature {
  title: string
  description: string
}

/**
 * Props for the internal FeatureCard sub-component.
 * id is optional (?) because only the recruiter card needs it.
 */
interface FeatureCardProps {
  id?: string
  badge: string
  title: string
  subtitle: string
  features: Feature[]
  badgeClass: string
}

